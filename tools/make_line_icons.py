"""Turns the LapDock icon pack's SVGs into src/LapDock/Controls/LineIcons.cs.

The icons are 48x48 stroke drawings (3 px round strokes) with a few filled dots. Each SVG becomes two
WPF path strings: what to stroke and what to fill. LineIcon draws them in the current text colour.

    python tools/make_line_icons.py            # reads assets/icons/svg/*.svg
"""
import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SVG_DIR = ROOT / "assets" / "icons" / "svg"
OUT = ROOT / "src" / "LapDock" / "Controls" / "LineIcons.cs"


def f(v):
    return float(v)


def circle(cx, cy, r):
    return f"M{cx - r:g},{cy} A{r:g},{r:g} 0 1 0 {cx + r:g},{cy} A{r:g},{r:g} 0 1 0 {cx - r:g},{cy} Z"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx:g},{cy} A{rx:g},{ry:g} 0 1 0 {cx + rx:g},{cy} A{rx:g},{ry:g} 0 1 0 {cx - rx:g},{cy} Z"


def rect(x, y, w, h, rx):
    if rx <= 0:
        return f"M{x:g},{y:g} H{x + w:g} V{y + h:g} H{x:g} Z"
    rx = min(rx, w / 2, h / 2)
    return (f"M{x + rx:g},{y:g} H{x + w - rx:g} A{rx:g},{rx:g} 0 0 1 {x + w:g},{y + rx:g} "
            f"V{y + h - rx:g} A{rx:g},{rx:g} 0 0 1 {x + w - rx:g},{y + h:g} "
            f"H{x + rx:g} A{rx:g},{rx:g} 0 0 1 {x:g},{y + h - rx:g} "
            f"V{y + rx:g} A{rx:g},{rx:g} 0 0 1 {x + rx:g},{y:g} Z")


def points(pts, close):
    nums = pts.replace(",", " ").split()
    pairs = [f"{nums[i]},{nums[i + 1]}" for i in range(0, len(nums), 2)]
    return "M" + pairs[0] + " " + " ".join("L" + p for p in pairs[1:]) + (" Z" if close else "")


def shape(el):
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        return circle(f(a["cx"]), f(a["cy"]), f(a["r"]))
    if tag == "ellipse":
        return ellipse(f(a["cx"]), f(a["cy"]), f(a["rx"]), f(a["ry"]))
    if tag == "rect":
        return rect(f(a.get("x", 0)), f(a.get("y", 0)), f(a["width"]), f(a["height"]), f(a.get("rx", a.get("ry", 0))))
    if tag == "polygon":
        return points(a["points"], True)
    if tag == "polyline":
        return points(a["points"], False)
    if tag == "line":
        return f"M{a['x1']},{a['y1']} L{a['x2']},{a['y2']}"
    return None


def convert(svg):
    stroke, fill = [], []

    def walk(el, inherited):
        style = dict(inherited)
        for k in ("fill", "stroke"):
            if k in el.attrib:
                style[k] = el.attrib[k]
        d = shape(el)
        if d:
            (fill if style.get("stroke") == "none" and style.get("fill") != "none" else stroke).append(d)
        for child in el:
            walk(child, style)

    walk(ET.parse(svg).getroot(), {"fill": "black", "stroke": "none"})
    return " ".join(stroke), " ".join(fill)


def main():
    rows = []
    for svg in sorted(SVG_DIR.glob("*.svg")):
        s, fl = convert(svg)
        rows.append(f'        ["{svg.stem}"] = ("{s}", "{fl}"),')
    OUT.write_text(
        "// Generated by tools/make_line_icons.py from assets/icons/svg — edit the SVGs, not this file.\n"
        "namespace LapDock.Controls;\n\n"
        "public sealed partial class LineIcon\n{\n"
        "    /// <summary>name → (path data to stroke, path data to fill), on a 48×48 grid.</summary>\n"
        "    private static readonly Dictionary<string, (string Stroke, string Fill)> Paths = new()\n    {\n"
        + "\n".join(rows) + "\n    };\n}\n",
        encoding="utf-8", newline="\r\n")
    print(f"{len(rows)} icons -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
